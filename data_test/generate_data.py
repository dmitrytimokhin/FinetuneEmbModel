def main():
    # ── Этап 1: TSDAE corpus ─────────────────────────────────────────────────
    corpus_path = BASE / "stage1_tsdae" / "corpus.csv"
    df_corpus = pd.DataFrame({"sentence": STAGE1_CORPUS})
    df_corpus.to_csv(corpus_path, index=False, encoding="utf-8")
    print(f"[stage1] corpus.csv  →  {len(df_corpus)} строк  →  {corpus_path}")

    # ── Этап 2: Supervised triplets ──────────────────────────────────────────
    random.shuffle(STAGE2_TRIPLETS)
    split = int(len(STAGE2_TRIPLETS) * 0.8)
    train_data = STAGE2_TRIPLETS[:split]
    eval_data  = STAGE2_TRIPLETS[split:]

    train_path = BASE / "stage2_supervised" / "train.csv"
    eval_path  = BASE / "stage2_supervised" / "eval.csv"

    df_train = pd.DataFrame(train_data)
    df_eval  = pd.DataFrame(eval_data)

    df_train.to_csv(train_path, index=False, encoding="utf-8")
    df_eval.to_csv(eval_path,  index=False, encoding="utf-8")

    print(f"[stage2] train.csv   →  {len(df_train)} строк  →  {train_path}")
    print(f"[stage2] eval.csv    →  {len(df_eval)} строк   →  {eval_path}")

    # ── Сводка ───────────────────────────────────────────────────────────────
    print("\n── Сводка по данным ──────────────────────────────────────────────")
    print(f"Этап 1 (TSDAE):      {len(df_corpus)} сырых чанков")
    print(f"Этап 2 train:        {len(df_train)} триплетов")
    print(f"Этап 2 eval:         {len(df_eval)}  триплетов")

    topics_in_train = set()
    for row in train_data:
        # грубая эвристика по ключевым словам
        for kw, label in [("ипотек","Ипотека"),("вклад","Вклады"),("карт","Карты"),
                          ("кредит","Кредиты"),("РКО","РКО"),("перевод","Переводы"),
                          ("страхов","Страхование"),("инвестиц","Инвестиции"),("ИИС","Инвестиции")]:
            if kw.lower() in row["anchor"].lower() or kw.lower() in row["positive"].lower():
                topics_in_train.add(label)
    print(f"Покрытые темы:       {', '.join(sorted(topics_in_train))}")

    print("\nПример триплета из train:")
    ex = df_train.iloc[0]
    print(f"  anchor  : {ex['anchor']}")
    print(f"  positive: {ex['positive'][:80]}...")
    print(f"  negative: {ex['negative'][:80]}...")


if __name__ == "__main__":
    main()
